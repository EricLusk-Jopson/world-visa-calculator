const BY_CODE = new Map(EES_COUNTRIES.map((c) => [c.code, c.name]));

/** "ES" → "Spain"; unknown or missing → "the country you left from". */
export function eesCountryName(code?: string | null): string {
  return (code && BY_CODE.get(code)) || "the country you left from";
}
